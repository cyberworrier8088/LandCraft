fn fade(t: f32) -> f32 {
    t * t * t * (t * (t * 6.0 - 15.0) + 10.0)
}

fn lerp(a: f32, b: f32, t: f32) -> f32 {
    a + t * (b - a)
}

fn grad(hash: usize, x: f32, y: f32) -> f32 {
    let h = hash & 7;
    let u = if h < 4 { x } else { y };
    let v = if h < 4 { y } else { x };
    let g_u = if (h & 1) != 0 { -u } else { u };
    let g_v = if (h & 2) != 0 { -v } else { v };
    g_u + g_v
}

pub fn noise(x: f32, y: f32) -> f32 {
    let x_floor = x.floor();
    let y_floor = y.floor();
    let xi = (x_floor as i32 & 255) as usize;
    let yi = (y_floor as i32 & 255) as usize;
    
    let xf = x - x_floor;
    let yf = y - y_floor;
    
    let u = fade(xf);
    let v = fade(yf);
    
    let aa = PERM[PERM[xi] + yi];
    let ab = PERM[PERM[xi] + yi + 1];
    let ba = PERM[PERM[xi + 1] + yi];
    let bb = PERM[PERM[xi + 1] + yi + 1];
    
    let x1 = lerp(grad(aa, xf, yf), grad(ba, xf - 1.0, yf), u);
    let x2 = lerp(grad(ab, xf, yf - 1.0), grad(bb, xf - 1.0, yf - 1.0), u);
    
    (lerp(x1, x2, v) + 1.0) * 0.5
}

pub fn terrain_height(x: i32, z: i32) -> i32 {
    let mut height = 0.0;
    let mut freq = 0.05; // adjusting for hill size
    let mut amp = 1.0; // adjusting for hill height
    
    for _ in 0..3 {
        height += noise(x as f32 * freq, z as f32 * freq) * amp;
        freq *= 2.0;
        amp *= 0.5;
    }

    (height * 20.0) as i32 
}